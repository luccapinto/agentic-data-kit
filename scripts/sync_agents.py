"""
sync_agents.py
==============
Compile `.agent/` (the source of truth, Antigravity layout) into every supported tool's
NATIVE layout. This is a translation, not a byte copy:

  SOURCE  : .agent/{agents,skills,workflows,rules/rules.md}
  COPILOT : .github/agents/*.agent.md (name, description, tools mapped to Copilot aliases)
            .github/skills/ | .github/prompts/*.prompt.md | .github/copilot-instructions.md
  CLAUDE  : .claude/agents/*.md (verbatim) | .claude/skills/ | .claude/workflows/
            .claude/commands/ (native slash commands) | .claude/CLAUDE.md (rules + commands)
  OPENCODE: .opencode/agents/*.md (mode: subagent + permission) | .opencode/skills/
            .opencode/commands/
  CURSOR  : .cursor/rules/*.mdc (alwaysApply) | .cursor/commands/*.md | .cursor/skills/
  ROOT    : AGENTS.md (rules) -> read by OpenCode, OpenAI Codex, Cursor and others.

Usage:
  python3 scripts/sync_agents.py           # regenerate every managed path
  python3 scripts/sync_agents.py --check   # exit 1 if any managed path is stale (CI)

Compatibility notes:
  - `trigger: always_on` in `.agent/rules/rules.md` is Antigravity-only; it is stripped from
    every generated rules file.
  - OpenCode reads the ROOT AGENTS.md, so `.opencode/AGENTS.md` is never generated (and is
    deleted if a legacy copy exists).
  - `.github/workflows/` is not managed here; CI files live there untouched.
"""

from __future__ import annotations

import argparse
import filecmp
import re
import shutil
import sys
import tempfile
from pathlib import Path

import yaml  # pip install pyyaml

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")

ROOT = Path(__file__).resolve().parent.parent

SOURCE = ROOT / ".agent"
AGENTS_SRC = SOURCE / "agents"
SKILLS_SRC = SOURCE / "skills"
WORKFLOWS_SRC = SOURCE / "workflows"
RULES_SRC = SOURCE / "rules" / "rules.md"

GENERATED_HEADER = "<!-- Auto-generated by scripts/sync_agents.py — DO NOT EDIT MANUALLY -->\n\n"

# Every path (relative to the repo root) owned by this script. Anything here is deleted and
# rebuilt on sync, and compared on --check.
MANAGED = [
    ".github/agents",
    ".github/skills",
    ".github/prompts",
    ".github/copilot-instructions.md",
    ".claude/agents",
    ".claude/skills",
    ".claude/workflows",
    ".claude/commands",
    ".claude/CLAUDE.md",
    ".opencode/agents",
    ".opencode/skills",
    ".opencode/commands",
    ".cursor/rules",
    ".cursor/commands",
    ".cursor/skills",
    "AGENTS.md",
]
# Paths that must NOT exist after a sync (older layouts).
LEGACY = [".opencode/AGENTS.md"]

# Short description used in the frontmatter of the always-on Cursor rule.
RULES_DESCRIPTION = (
    "Agentic Data Kit — always-on operating rules: skills first, the Power BI Desktop-open "
    "loop with independent visual review, data engineering principles (idempotency, "
    "Write-Audit-Publish, PII masking) and the data debugging reference."
)

# Claude-style tool names (used in `.agent/agents/*.md`) -> GitHub Copilot custom-agent tool
# aliases. Unknown names are an error: silently dropping a tool would change what the agent
# is allowed to do.
COPILOT_TOOL_ALIASES = {
    "read": "read",
    "notebookread": "read",
    "grep": "search",
    "glob": "search",
    "edit": "edit",
    "multiedit": "edit",
    "write": "edit",
    "notebookedit": "edit",
    "bash": "execute",
    "webfetch": "web",
    "websearch": "web",
    "task": "agent",
    "todowrite": "todo",
}


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------
def parse_frontmatter(text: str) -> tuple[dict, str]:
    """Split YAML frontmatter from the body. Returns ({}, text) when there is none."""
    match = re.match(r"^---\s*\n(.*?)\n---\s*\n", text, re.DOTALL)
    if not match:
        return {}, text
    try:
        meta = yaml.safe_load(match.group(1)) or {}
    except yaml.YAMLError:
        meta = {}
    return meta, text[match.end():]


def first_sentence(text: str) -> str:
    """First meaningful body line (skips headings and separators)."""
    for line in text.splitlines():
        line = line.strip()
        if line and not line.startswith("#") and not line.startswith("---"):
            clean = re.sub(r"[*_`>\[\]]", "", line).strip()
            if clean:
                return clean[:120]
    return "Agent logic"


def to_title_case(slug: str) -> str:
    """'pbi-visual-reviewer' -> 'Pbi Visual Reviewer'."""
    return slug.replace("-", " ").replace("_", " ").title()


def strip_frontmatter(text: str) -> str:
    _, body = parse_frontmatter(text)
    return body.lstrip()


def split_tools(tools_val) -> list[str]:
    if not tools_val:
        return []
    if isinstance(tools_val, list):
        items = tools_val
    else:
        items = str(tools_val).split(",")
    return [str(t).strip() for t in items if str(t).strip()]


def copilot_tools(tools_val, agent: str) -> list[str]:
    """Map Claude-style tool names to Copilot aliases, keeping first-seen order."""
    mapped: list[str] = []
    for tool in split_tools(tools_val):
        alias = COPILOT_TOOL_ALIASES.get(tool.lower())
        if alias is None:
            raise SystemExit(
                f"error: agent '{agent}' declares tool '{tool}' with no Copilot mapping; "
                "add it to COPILOT_TOOL_ALIASES in scripts/sync_agents.py"
            )
        if alias not in mapped:
            mapped.append(alias)
    return mapped


def opencode_permission(tools_val) -> dict:
    """Map the source `tools` allow-list to OpenCode's coarse `permission` block.

    OpenCode gates `edit` and `bash`; read/grep/glob are always allowed.
    """
    tools = {t.lower() for t in split_tools(tools_val)}
    if not tools:
        return {}
    return {
        "edit": "allow" if tools & {"edit", "write", "multiedit", "notebookedit"} else "deny",
        "bash": "allow" if "bash" in tools else "deny",
    }


def dump_frontmatter(meta: dict) -> str:
    return yaml.dump(meta, allow_unicode=True, default_flow_style=False, sort_keys=False).strip()


def write(path: Path, text: str) -> None:
    """Write UTF-8 with LF line endings on every OS so --check is platform-independent."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(text.encode("utf-8"))


def rules_body() -> str:
    return strip_frontmatter(RULES_SRC.read_text(encoding="utf-8"))


def source_files(folder: Path) -> list[Path]:
    return sorted(folder.glob("*.md")) if folder.exists() else []


def copy_skills(dest: Path) -> None:
    shutil.copytree(SKILLS_SRC, dest, ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))


# ---------------------------------------------------------------------------
# Builders — each writes one tool's layout under `out` (a repo root or a temp dir)
# ---------------------------------------------------------------------------
def build_copilot(out: Path) -> None:
    gh = out / ".github"
    for src in source_files(AGENTS_SRC):
        meta, body = parse_frontmatter(src.read_text(encoding="utf-8"))
        fm: dict = {
            "name": meta.get("name") or to_title_case(src.stem),
            "description": meta.get("description") or first_sentence(body),
        }
        tools = copilot_tools(meta.get("tools"), src.stem)
        if tools:
            fm["tools"] = tools
        write(gh / "agents" / f"{src.stem}.agent.md", f"---\n{dump_frontmatter(fm)}\n---\n\n{body.lstrip()}")

    copy_skills(gh / "skills")

    for src in source_files(WORKFLOWS_SRC):
        meta, body = parse_frontmatter(src.read_text(encoding="utf-8"))
        fm = {
            "name": src.stem,
            "description": meta.get("description") or f"Workflow: {to_title_case(src.stem)}",
        }
        write(
            gh / "prompts" / f"{src.stem}.prompt.md",
            f"---\n{dump_frontmatter(fm)}\n---\n\n**Context:** ${{selection}}\n\n{body.lstrip()}",
        )

    write(gh / "copilot-instructions.md", GENERATED_HEADER + rules_body())


def build_claude(out: Path) -> None:
    cl = out / ".claude"
    for src in source_files(AGENTS_SRC):
        write(cl / "agents" / src.name, src.read_text(encoding="utf-8"))

    copy_skills(cl / "skills")
    shutil.copytree(WORKFLOWS_SRC, cl / "workflows")
    for src in source_files(WORKFLOWS_SRC):
        write(cl / "commands" / src.name, src.read_text(encoding="utf-8"))

    commands = []
    for src in source_files(WORKFLOWS_SRC):
        meta, _ = parse_frontmatter(src.read_text(encoding="utf-8"))
        description = meta.get("description") or to_title_case(src.stem)
        commands.append(
            f"- **/{src.stem}**: {description} "
            f"— Load context from `.claude/workflows/{src.name}` and follow its steps."
        )
    write(
        cl / "CLAUDE.md",
        GENERATED_HEADER
        + rules_body().rstrip()
        + "\n\n---\n\n## Custom Commands & Workflows\n\n"
        + "The following slash commands are available. When triggered, load the referenced\n"
        + "workflow file and follow its instructions step by step.\n\n"
        + "\n".join(commands)
        + "\n",
    )


def build_opencode(out: Path) -> None:
    oc = out / ".opencode"
    for src in source_files(AGENTS_SRC):
        meta, body = parse_frontmatter(src.read_text(encoding="utf-8"))
        fm: dict = {"description": meta.get("description") or first_sentence(body), "mode": "subagent"}
        perm = opencode_permission(meta.get("tools"))
        if perm:
            fm["permission"] = perm
        write(oc / "agents" / src.name, f"---\n{dump_frontmatter(fm)}\n---\n\n{body.lstrip()}")

    copy_skills(oc / "skills")
    for src in source_files(WORKFLOWS_SRC):
        write(oc / "commands" / src.name, src.read_text(encoding="utf-8"))


def build_cursor(out: Path) -> None:
    cu = out / ".cursor"
    fm = {"description": RULES_DESCRIPTION, "globs": "", "alwaysApply": True}
    write(cu / "rules" / "agentic-data-kit.mdc", f"---\n{dump_frontmatter(fm)}\n---\n\n{rules_body()}")
    for src in source_files(WORKFLOWS_SRC):
        write(cu / "commands" / src.name, src.read_text(encoding="utf-8"))
    copy_skills(cu / "skills")


def build_root(out: Path) -> None:
    write(out / "AGENTS.md", GENERATED_HEADER + rules_body())


def build(out: Path) -> None:
    if not RULES_SRC.exists():
        raise SystemExit(f"error: missing {RULES_SRC.relative_to(ROOT)}")
    build_copilot(out)
    build_claude(out)
    build_opencode(out)
    build_cursor(out)
    build_root(out)


# ---------------------------------------------------------------------------
# Sync and check
# ---------------------------------------------------------------------------
def remove(path: Path) -> None:
    if path.is_dir():
        shutil.rmtree(path)
    elif path.exists():
        path.unlink()


def files_under(path: Path) -> set[str]:
    if path.is_file():
        return {""}
    if not path.is_dir():
        return set()
    return {
        p.relative_to(path).as_posix()
        for p in path.rglob("*")
        if p.is_file() and "__pycache__" not in p.parts
    }


def stale_paths(expected_root: Path, actual_root: Path) -> list[str]:
    """Managed files that differ between a fresh build and the working tree."""
    problems: list[str] = []
    for rel in MANAGED:
        exp, act = expected_root / rel, actual_root / rel
        exp_files, act_files = files_under(exp), files_under(act)
        for f in sorted(exp_files | act_files):
            shown = f"{rel}/{f}" if f else rel
            if f not in act_files:
                problems.append(f"missing  {shown}")
            elif f not in exp_files:
                problems.append(f"extra    {shown}")
            elif not filecmp.cmp(exp / f if f else exp, act / f if f else act, shallow=False):
                problems.append(f"outdated {shown}")
    for rel in LEGACY:
        if (actual_root / rel).exists():
            problems.append(f"legacy   {rel}")
    return problems


def sync(root: Path = ROOT) -> None:
    for rel in MANAGED + LEGACY:
        remove(root / rel)
    build(root)


def check(root: Path = ROOT) -> list[str]:
    with tempfile.TemporaryDirectory(prefix="adk-sync-") as tmp:
        build(Path(tmp))
        return stale_paths(Path(tmp), root)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Compile .agent/ into every tool's native layout.")
    parser.add_argument("--check", action="store_true", help="exit 1 if generated folders are stale")
    args = parser.parse_args(argv)

    if args.check:
        problems = check()
        if problems:
            print("Generated folders are stale. Run: python3 scripts/sync_agents.py")
            for line in problems:
                print(f"  {line}")
            return 1
        print(f"OK: {len(MANAGED)} managed paths match .agent/")
        return 0

    sync()
    agents = [p.stem for p in source_files(AGENTS_SRC)]
    skills = sorted(p.name for p in SKILLS_SRC.iterdir() if p.is_dir())
    workflows = [p.stem for p in source_files(WORKFLOWS_SRC)]
    print("Synced .agent/ -> .github/ .claude/ .opencode/ .cursor/ AGENTS.md")
    print(f"  agents    ({len(agents)}): {', '.join(agents) or '-'}")
    print(f"  skills    ({len(skills)}): {', '.join(skills)}")
    print(f"  workflows ({len(workflows)}): {', '.join(workflows)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
